<?php

namespace App\Modules\Sessions\Attendance\Signing;

use App\Http\Controllers\Controller;
use App\Modules\Core\Access\AccessScope;
use App\Modules\Core\Access\Scopes;
use App\Modules\Core\Documents\PdfRenderingFailed;
use App\Modules\Core\Tenancy\TenantStorage;
use App\Modules\Core\Users\User;
use App\Modules\Sessions\Attendance\Months;
use App\Modules\Sessions\Permissions;
use App\Modules\Sessions\Planning\Seance;
use App\Modules\Sessions\SessionsVisibility;
use App\Modules\Sessions\Sessions\TrainingSession;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Storage;
use Illuminate\Support\Str;
use Illuminate\Validation\ValidationException;
use Symfony\Component\HttpFoundation\StreamedResponse;

/**
 * The archived signed sheets of a session: generated by a manager of the
 * attendance (sessions.attendance.manage with a scope other than « Ses
 * séances », on the session), downloaded by whoever reaches one of its
 * séances with that right (404 otherwise), always from the archive checked
 * against its SHA-256 (410 when lost or altered).
 */
class SignedSheetController extends Controller
{
    public function __construct(private readonly SignedSheetPdf $pdf) {}

    /**
     * @throws PdfRenderingFailed
     */
    public function store(Request $request, TrainingSession $trainingSession): JsonResponse
    {
        $user = self::user($request);
        abort_if(Scopes::of($user, Permissions::ATTENDANCE_MANAGE) === AccessScope::Trainer
            || ! SessionsVisibility::allows($user, Permissions::ATTENDANCE_MANAGE, $trainingSession), 403);
        $month = $request->input('month');
        if (! is_string($month) || ! in_array($month, Months::ofSession($trainingSession), true)) {
            throw ValidationException::withMessages(['month' => 'Choisissez un mois de la session.']);
        }
        $first = Months::parse($month) ?? throw ValidationException::withMessages(['month' => 'Choisissez un mois de la session.']);
        $this->pdf->generate($trainingSession, $first, $user);

        return response()->json(['sheets' => self::list($trainingSession->id)], 201)->header('Cache-Control', 'no-store, private');
    }

    public function show(Request $request, string $sheet): StreamedResponse
    {
        abort_unless(Str::isUuid($sheet), 404);
        $row = SignedSheet::query()->find($sheet) ?? abort(404);
        abort_unless(SessionsVisibility::seances(Seance::query()->where('training_session_id', $row->training_session_id), self::user($request), Permissions::ATTENDANCE_MANAGE)->exists(), 404);
        $disk = Storage::disk(TenantStorage::DISK);
        $bytes = $disk->exists($row->path) ? (string) $disk->get($row->path) : null;
        abort_if($bytes === null || hash('sha256', $bytes) !== $row->pdf_sha256, 410);

        return response()->stream(function () use ($bytes): void {
            echo $bytes;
        }, 200, [
            'Content-Type' => 'application/pdf',
            'Content-Disposition' => 'attachment; filename="emargement-signe-'.$row->month->format('Y-m').'.pdf"',
            'Content-Length' => (string) strlen($bytes),
            'Cache-Control' => 'private, no-store',
            'X-Content-Type-Options' => 'nosniff',
        ]);
    }

    /**
     * The versions of a session, the latest first.
     *
     * @return list<array<string, mixed>>
     */
    public static function list(string $sessionId): array
    {
        return SignedSheet::query()->where('training_session_id', $sessionId)->orderByDesc('created_at')->orderByDesc('id')->get()
            ->map(fn (SignedSheet $s) => [
                'id' => $s->id,
                'month' => $s->month->format('Y-m'),
                'month_label' => Months::label($s->month->format('Y-m')),
                'generated_at' => $s->created_at?->toIso8601String(),
                'sha256' => $s->pdf_sha256,
                'url' => route('signed-sheets.show', $s->id),
            ])->values()->all();
    }

    private static function user(Request $request): User
    {
        $user = $request->user();
        assert($user instanceof User);

        return $user;
    }
}
